'''
教學：% 是取餘數，例如 7 % 2 的結果是 1，8 % 2 的結果是 0。
== 用來比較兩個值是否相等；如果除以 2 的餘數是 0，數字就是偶數。
input() 的結果是文字，使用 int() 轉成整數後才能做數學運算。
'''

'''
題目 8：判斷奇數或偶數
使用 input() 詢問使用者輸入一個整數，並將輸入轉成整數。
使用 if/else 和 %（取餘數）判斷：
- 如果數字除以 2 的餘數是 0，印出「這是偶數」
- 否則印出「這是奇數」
例如輸入 7，程式應印出「這是奇數」。
'''

name = int(input("請輸入一個整數："))
if name % 2 == 0:
    print("這是偶數")
else:
    print("這是奇數")
