'''
教學：max() 會找出數字清單中的最大值，min() 會找出最小值。
範例：
river_lengths = [18, 7, 24]
print(max(river_lengths))
print(min(river_lengths))
這會分別印出清單中最大的數字和最小的數字。
'''

'''
題目 25：找出最高和最低分
建立 scores 清單，放入 72、88、91、65。
使用 max() 和 min() 分別印出最高分與最低分。
'''

scores = [72 , 88 , 91 , 65]
print(max(scores))
print(min(scores))
