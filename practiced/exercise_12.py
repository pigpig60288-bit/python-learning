'''
教學：append() 可以把一個新項目加到 list 的最後面。
範例：
pets = ["貓", "狗"]
pets.append("兔子")
print(pets)  # 印出 ['貓', '狗', '兔子']
append() 會直接改變原本的清單，不需要另外建立一個清單。
'''

'''
題目 12：更新喜歡的運動清單
建立一個 sports 清單，先放入兩種你喜歡的運動。
使用 append() 再加入第三種運動，最後印出整個清單。
預期結果需包含你選的三種運動，並以 list 的格式印出。
'''

sports = ["游泳","羽毛球"]
sports.append("排球")
print(sports)
