'''
教學：變數用來保存資料，例如 name = "小明"。print() 可以印出文字。
用 + 可以把文字接在一起；若要把數字接到文字後，先用 str() 轉成文字。
'''

'''
題目 1：建立 name 和 age 兩個變數，印出「我叫○○，今年○歲。」。

標準輸入範例 1：
name = "野原新之助"
age = 5

預期輸出 1：
我叫野原新之助，今年5歲。

標準輸入範例 2：
name = "小明"
age = 12

預期輸出 2：
我叫小明，今年12歲。
'''

name = "野原新之助"
age = 5
print("我叫" + name + "，今年" + str(age) + "歲。")
