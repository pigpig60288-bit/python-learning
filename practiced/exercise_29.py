'''
教學：or 表示「或者」；左右條件中只要有一個成立，整體結果就是 True。
範例：
weather = "下雨"
if weather == "下雨" or weather == "下雪":
print("記得帶雨具")
下雨或下雪時都會印出提醒。
'''

'''
題目 29：判斷是否為週末
詢問使用者輸入星期幾，例如「星期六」或「星期三」。
如果輸入的是「星期六」或「星期日」，印出「今天是假日」；
其他輸入則印出「今天要上課」。
'''

day = input("今天是星期幾?")
if day == "星期六" or day == "星期日":
    print("今天是假日")
else:
    print("今天要上課")
