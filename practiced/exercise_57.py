'''
教學：for 迴圈可以逐項取出清單內容。每次迴圈執行時，變數會代表目前的項目。

範例：
colors = ["藍色", "綠色", "黃色"]
for color in colors:
    print(color)

這會一行一行印出每種顏色。
'''

'''
題目 57：收集旅行城市
使用 for 迴圈走訪 cities 清單，依序一行印出每個城市名稱。
請勿把城市名稱逐一寫成多個 print；清單內容以範例為準。

標準輸入範例 1：

cities = ["台北", "東京", "大阪"]

預期輸出 1：

台北
東京
大阪

標準輸入範例 2：

cities = ["首爾", "札幌", "香港"]

預期輸出 2：

首爾
札幌
香港
'''
cities = ["東京", "大阪", "神戶"]
for city in cities:
    print(city)