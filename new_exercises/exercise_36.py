# 教學：class 可以描述一類物件；依 class 建立出來的東西稱為物件。
# class 裡可以先放一個類別屬性，物件可以用「物件名稱.屬性名稱」讀取它。
# 範例：
# class Instrument:
#     family = "樂器"
#
# piano = Instrument()
# print(piano.family)
# Instrument() 建立一個 Instrument 物件；piano.family 讀取類別屬性。
