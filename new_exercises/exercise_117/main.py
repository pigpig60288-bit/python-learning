'''
教學：輸出清單時可以用索引控制分隔符號

走訪清單時，索引為 0 的項目之前不需要分隔符號；其他項目之前先印分隔符號：

labels = ["入口", "服務台", "出口"]
index = 0
while index < len(labels):
    if index > 0:
        print(" -> ", end="")
    print(labels[index], end="")
    index += 1
print()

'''

