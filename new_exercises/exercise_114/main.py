'''
教學：用 while 重複印出一行的內容

在每一行開始時把計數器設回起點，while 可以負責印出該行需要的符號：

row = 1
while row <= 2:
    mark = 0
    while mark < 4:
        print("=", end="")
        mark += 1
    print()
    row += 1

'''

