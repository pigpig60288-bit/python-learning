'''
教學：用 while 的索引倒著走訪清單

索引可以從清單最後一個位置開始，每次減少 1，直到索引小於 0：

colors = ["紅", "綠", "藍"]
index = len(colors) - 1
while index >= 0:
    print(colors[index])
    index -= 1

'''

