'''
教學：整數除法和取餘數可以逐位處理數字

// 會取得整數除法的商，% 會取得餘數。例如 47 // 10 是 4，47 % 10 是 7。
因此可以用它們分開一個兩位數的十位和個位：

number = 47
print(number // 10)
print(number % 10)

'''

