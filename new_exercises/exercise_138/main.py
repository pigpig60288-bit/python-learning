'''
教學：遞迴可以拆解代碼中的各位數字

% 取得最右邊的數字，// 移除最右邊的數字。
把最右邊的數字加上剩下部分的位數總和；小於 10 時就是停止條件：

def sum_code_digits(code):
    if code < 10:
        return code
    return code % 10 + sum_code_digits(code // 10)

print(sum_code_digits(726))

'''

