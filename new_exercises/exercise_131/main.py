'''
教學：函式可以呼叫自己，這叫做遞迴

遞迴函式要有停止條件，否則會一直呼叫自己。每次呼叫時，也要讓參數
逐漸靠近停止條件：

def water_plants(count):
    if count > 0:
        print("澆一盆")
        water_plants(count - 1)

water_plants(3)

當 count 變成 0 時，if 條件不成立，函式就不會再呼叫自己。
'''

