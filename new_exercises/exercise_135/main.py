'''
教學：建立遞迴的基礎值

有些遞迴計算在參數到達某個值時，答案是固定的。這個答案就是停止時回傳的基礎值：

def count_down_steps(number):
    if number == 0:
        return 0
    return 1 + count_down_steps(number - 1)

'''

