'''
教學：把不同工作分配給巢狀迴圈

外層控制每一行，內層可以先印空格，再印符號；每部分都用 end="" 留在同一行：

for row in range(1, 3):
    print(" ", end="")
    count = 0
    while count < row:
        print("*", end="")
        count += 1
    print()

'''

