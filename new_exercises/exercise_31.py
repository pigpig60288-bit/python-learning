# 選擇方式：從「簡單、普通、困難」中挑一個等級完成。
# 每題都要自己寫程式；先不要看別人的解答。
#
# ── 簡單：計算飲料費用 ──
# 詢問使用者飲料單價和購買杯數，將輸入轉成整數並算出總價。
# 如果總價大於或等於 200 元，印出「金額達 200 元」；
# 否則印出「金額未達 200 元」。最後印出總價。
#
# ── 普通：收集旅行地點 ──
# 建立空的 places 清單，重複詢問使用者輸入想去的地點。
# 使用者輸入「完成」時結束，且不要把「完成」放進清單。
# 結束後印出所有地點。
#
# ── 困難：成績統計與等級判斷 ──
# 使用者可重複輸入 0 到 100 的整數成績；輸入 -1 表示結束，
# 不要把 -1 加進清單。假設其他輸入一定是 0 到 100 的整數。
# 每個成績加入 scores 清單，並用變數累計總分和成績筆數。
# 結束後，如果沒有輸入任何成績，印出「沒有成績」。
# 否則計算平均分數，並依平均分數印出等級：
#   - 大於或等於 90：A
#   - 大於或等於 80：B
#   - 大於或等於 70：C
#   - 其他：D
# 最後也印出 scores 清單、平均分數和等級。
