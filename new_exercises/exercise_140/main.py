'''
教學：多個遞迴呼叫可以組成一個完整流程

有些任務需要先完成一個較小部分，再處理目前的工作，最後完成另一個較小部分。
每個遞迴呼叫都要減少問題規模，並且在最小情況停止。

例如檢查多層盒子時，可以先檢查較小的一層、處理目前這層，再檢查另一個較小的部分：

def inspect(level):
    if level > 0:
        inspect(level - 1)
        print("檢查一個盒子")
        inspect(level - 1)

'''

