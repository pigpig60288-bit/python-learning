'''
教學：讓 range() 倒著計數

range() 可以加入第三個數字表示每次改變的量。步進值是 -1 時，數字會倒著減少：

for minute in range(4, 0, -1):
    print(minute)

這個範例會印出 4、3、2、1；range() 的結尾仍然不包含在結果中。
'''

