'''
教學：使用巢狀 for 迴圈

一個 for 迴圈裡面可以再放另一個 for 迴圈。外層每執行一次，內層就會完整執行一次：

for shelf in range(1, 3):
    for box in range(1, 4):
        print("檢查一個盒子")

上例會為每個架子檢查三個盒子。內層的 range(1, 4) 會產生 1、2、3。
'''

