'''
教學：一個遞迴函式可以呼叫自己兩次

有些問題可以拆成兩個較小問題，再合併兩個結果。每個分支都要逐漸靠近停止條件：

def inspect_boxes(level):
    if level > 0:
        inspect_boxes(level - 1)
        print(f"完成第 {level} 層")
        inspect_boxes(level - 1)

'''

