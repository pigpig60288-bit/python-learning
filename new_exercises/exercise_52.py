# 教學：__init__ 可以接收多個資料，分別存成物件屬性。
# 之後可用「物件.屬性名稱」讀取各項資料。
# 範例：
# class Desk:
#     def __init__(self, material, drawers):
#         self.material = material
#         self.drawers = drawers
#
# desk = Desk("木頭", 3)
# print(desk.material)
# print(desk.drawers)
# 這個物件分別保存材質和抽屜數。
