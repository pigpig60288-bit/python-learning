'''
教學：計算符合條件的項目數量時，先用 0 當計數器；每次符合條件就加 1。

範例：
ages = [12, 17, 21]
count = 0
for age in ages:
    if age >= 18:
        count += 1

print(f"成年人數：{count}")
'''

