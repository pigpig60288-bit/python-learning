'''
教學：遞迴處理清單時，可以把索引當成參數

每次呼叫都處理目前索引，再把索引加 1；索引到達清單長度時停止：

labels = ["入口", "走廊", "出口"]
def show_labels(index):
    if index < len(labels):
        print(labels[index])
        show_labels(index + 1)

show_labels(0)

'''

