# 教學：if/elif/else 可以依序檢查多種條件；第一個成立的區塊會執行。
# elif 是「否則如果」，else 是前面條件都不成立時執行。
# 由高分門檻往低分門檻檢查，並使用 >= 表示「大於或等於」。
#
# 題目 9：判斷成績等級
# 使用 input() 詢問使用者輸入 0 到 100 的整數成績，並將輸入轉成整數。
# 使用 if/elif/else 判斷並印出等級：
#   - 90 到 100：印出「A」
#   - 80 到 89：印出「B」
#   - 70 到 79：印出「C」
#   - 60 到 69：印出「D」
#   - 0 到 59：印出「F」
# 例如輸入 85，程式應印出「B」。
# 先假設使用者一定會輸入 0 到 100 之間的整數。
grade=int(input("請輸入你的成績（0-100）："))
if grade >= 90:
    print("A")
elif grade>= 80:
    print("B")
elif grade>= 70:
    print("C")
elif grade>= 60:
    print("D")
else:
    print("F")